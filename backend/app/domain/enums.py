class Urgency(StrEnum):
    ROUTINE = "ROUTINE"
    URGENT = "URGENT"
    EMERGENCY = "EMERGENCY"

    @property
    def rank(self) -> int:
        return _URGENCY_RANK[self]

    @classmethod
    def max(cls, a: "Urgency", b: "Urgency") -> "Urgency":
        return a if a.rank >= b.rank else b


_URGENCY_RANK = {Urgency.ROUTINE: 0, Urgency.URGENT: 1, Urgency.EMERGENCY: 2}


