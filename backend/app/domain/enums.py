class WorkflowState(StrEnum):
    COLLECTING_INFORMATION = "COLLECTING_INFORMATION"
    READY_FOR_DECISION = "READY_FOR_DECISION"
    JEV_PROCESSING = "JEV_PROCESSING"
    EXECUTING_ACTION = "EXECUTING_ACTION"
    COMPLETED = "COMPLETED"
    ESCALATED = "ESCALATED"
    ERROR = "ERROR"

    @property
    def is_terminal(self) -> bool:
        return self in {WorkflowState.COMPLETED, WorkflowState.ESCALATED, WorkflowState.ERROR}


